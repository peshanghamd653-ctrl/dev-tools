// Finds orphaned ts-rs bindings: files in src/shared/ipc/bindings/ that no
// Rust DTO generates any more.
//
//   pnpm check:bindings
//
// Why this is a separate check rather than part of the existing one.
//
// CI already regenerates the bindings and diffs them ("Bindings up to date" in
// the `rust` job of .github/workflows/ci.yml). That catches a DTO whose shape
// *changed*, and — via `git add --intent-to-add` — a DTO that is *new*. It is
// structurally blind to a DTO that was *deleted*: nothing regenerates over the
// leftover .ts file, so it stays byte-identical to what was committed, the diff
// is empty, and the gate is green. Regenerate-and-diff can only ever compare
// files that something wrote; a file nothing writes is invisible to it.
//
// That silence is the expensive part. The stale type keeps type-checking and
// keeps being importable, so the frontend can go on speaking a protocol the
// backend no longer implements and `tsc` will agree with it. The failure shows
// up at run time as an IPC command that does not exist, on a build where every
// gate was green. Only an inventory comparison finds it, which is what this is.
//
// Where the expected inventory comes from, and why not from the Rust sources.
//
// A regex over `#[derive(TS)]` would re-implement ts-rs's rules and then drift
// from them. It cannot distinguish a plain derive from one carrying
// `#[ts(export)]` — only the latter emits a file. It does not see
// `#[ts(rename = "..")]`, which changes the emitted file name while leaving the
// Rust ident alone. It does not evaluate `cfg` gates, so a platform- or
// feature-gated DTO reads as exported on a run where it is not compiled at all.
// And it cannot know that ts-rs exports every *dependency* of an exported type
// too, whether or not that dependency asked to be exported. Each of those is a
// false accusation against a file that is fine, or a miss on one that is not.
//
// So ts-rs is asked instead of imitated. `default_out_dir()` in ts-rs 10 reads
// TS_RS_EXPORT_DIR with `std::env::var` at run time, inside the exporter rather
// than inside the derive macro — so pointing it at a scratch directory and
// re-running the same `export_bindings_*` tests regenerates the entire set
// somewhere harmless. Nothing recompiles (the variable is not baked into the
// macro expansion, so cargo's cache still hits) and the working tree is never
// written to. Whatever lands in the scratch directory is, by construction,
// exactly the set of files ts-rs generates today. A committed file whose name
// is not in that set is an orphan.

import { spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import process from "node:process";

const root = path.resolve(import.meta.dirname, "..");
const BINDINGS_DIR = path.join(root, "src", "shared", "ipc", "bindings");
const BINDINGS_REL = "src/shared/ipc/bindings";

// The first line ts-rs writes into every file it generates (`NOTE` in
// ts-rs/src/export.rs). Only files carrying it are candidates for orphanhood:
// anything hand-written that lives in this directory — a barrel `index.ts`, a
// hand-rolled helper — was never ts-rs output, so it will never appear in a
// regeneration and must not be reported as something a regeneration dropped.
// There is no such file today; this is here so that adding one is not a booby
// trap for whoever adds it.
const TS_RS_HEADER = "// This file was generated by [ts-rs]";

// ts-rs resolves each `#[ts(export_to = "../../../src/shared/ipc/bindings/")]`
// against TS_RS_EXPORT_DIR by popping the `..` components off it. The prefixes
// in this workspace are three levels deep for `crates/<crate>/` and four for
// `crates/modules/<crate>/`, and because a single environment variable serves
// every crate, the two land in *different* subdirectories of the scratch root —
// hence the recursive walk below rather than one readdir.
//
// The nesting is far past four so that popping stays inside the scratch root.
// Pop more components than there are and ts-rs writes outside it, where this
// script cannot see the file. That failure mode is loud rather than silent —
// every committed binding comes back an orphan at once — and the sanity check
// further down converts it into "the check could not run" rather than a page of
// false accusations.
//
// The segment is one character on purpose. This runs on Windows, where the
// non-verbatim path limit is 260 and Rust's `std::fs` does not silently promote
// paths past it; sixteen levels of headroom cost 32 characters this way and 112
// with a word for a name, and the scratch tree is deleted unread either way.
const NEST_DEPTH = 16;
const NEST_SEGMENT = "n";

/** Every `.ts` file under `dir`, recursively, as absolute paths. */
function collectTsFiles(dir) {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const abs = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...collectTsFiles(abs));
    else if (entry.isFile() && entry.name.endsWith(".ts")) out.push(abs);
  }
  return out;
}

/** Exit with a message that says the check itself did not run. */
function cannotRun(reason, detail) {
  console.error(`The orphan-bindings check could not run: ${reason}`);
  if (detail) console.error(`\n${detail}`);
  console.error(
    "\nThis is not a report about the bindings. Nothing was checked.",
  );
  process.exit(2);
}

// --- what is committed ------------------------------------------------------

if (!fs.existsSync(BINDINGS_DIR)) {
  cannotRun(`${BINDINGS_REL} does not exist.`);
}

/** @type {string[]} */
const committed = [];
/** @type {string[]} */
const notGenerated = [];

for (const entry of fs.readdirSync(BINDINGS_DIR, { withFileTypes: true })) {
  if (!entry.isFile() || !entry.name.endsWith(".ts")) continue;
  const head = fs.readFileSync(path.join(BINDINGS_DIR, entry.name), "utf8");
  if (head.startsWith(TS_RS_HEADER)) committed.push(entry.name);
  else notGenerated.push(entry.name);
}

if (committed.length === 0) {
  cannotRun(
    `${BINDINGS_REL} contains no ts-rs generated files.`,
    "Every file there should begin with the ts-rs header. Either the directory\n" +
      "is empty, or ts-rs changed the header it writes and this script needs\n" +
      "updating to match.",
  );
}

// --- what ts-rs generates today ---------------------------------------------

const scratchRoot = fs.mkdtempSync(path.join(os.tmpdir(), "devos-bindings-"));
const exportDir = path.join(
  scratchRoot,
  ...Array(NEST_DEPTH).fill(NEST_SEGMENT),
);
fs.mkdirSync(exportDir, { recursive: true });

/** @type {string[]} */
let generated;

try {
  // The same command `pnpm gen:types` runs, with the destination redirected.
  // `--quiet` because the interesting output is the file set, not 56 lines of
  // `test export_bindings_x ... ok`; the captured output is printed only if
  // cargo fails, where it is the whole story.
  const cargo = spawnSync(
    "cargo",
    ["test", "--workspace", "export_bindings", "--quiet"],
    {
      cwd: root,
      env: { ...process.env, TS_RS_EXPORT_DIR: exportDir },
      encoding: "utf8",
      // stdin inherited from the parent would leave cargo waiting on a TTY that
      // CI does not have.
      stdio: ["ignore", "pipe", "pipe"],
    },
  );

  if (cargo.error) {
    cannotRun(
      `could not run cargo (${cargo.error.message}).`,
      "This check regenerates the bindings, so it needs a working Rust\n" +
        "toolchain on PATH — same as `pnpm gen:types`.",
    );
  }
  if (cargo.status !== 0) {
    cannotRun(
      `\`cargo test --workspace export_bindings\` exited ${cargo.status}.`,
      `${cargo.stdout ?? ""}${cargo.stderr ?? ""}`.trim() ||
        "cargo produced no output.",
    );
  }

  generated = collectTsFiles(scratchRoot).map((f) => path.basename(f));
} finally {
  fs.rmSync(scratchRoot, { recursive: true, force: true });
}

// Comparison is by file name. Every `export_to` in the workspace points at the
// one flat directory, so within it the name is the identity — and the scratch
// tree deliberately does *not* mirror the repo layout (see NEST_DEPTH), so the
// paths themselves are not comparable.
const generatedNames = new Set(generated);

// --- sanity, before believing the answer ------------------------------------

if (generatedNames.size === 0) {
  cannotRun(
    "the regeneration produced no files at all.",
    "cargo succeeded but wrote nothing under the scratch directory. Either the\n" +
      "`export_bindings_*` tests no longer run under this filter, or ts-rs no\n" +
      "longer honours TS_RS_EXPORT_DIR at run time — in which case the real\n" +
      `bindings in ${BINDINGS_REL} may have been rewritten instead. Check\n` +
      "`git status` before trusting the working tree.",
  );
}

const recognised = committed.filter((name) => generatedNames.has(name));
if (recognised.length === 0) {
  cannotRun(
    "the regeneration and the committed directory have no file in common.",
    `${generatedNames.size} file(s) were generated and ${committed.length} are\n` +
      "committed, and not one name matches. That is not what drift looks like —\n" +
      "it is what a broken check looks like. The likeliest cause is that ts-rs\n" +
      "wrote outside the scratch root because an `export_to` prefix now climbs\n" +
      `more than ${NEST_DEPTH} levels; raise NEST_DEPTH in this script.`,
  );
}

// --- the answer -------------------------------------------------------------

const orphans = committed.filter((name) => !generatedNames.has(name));

// Reported, never failed on: a generated file that is not committed is the
// *other* direction of drift, and the "Bindings up to date" step already owns
// it — with a full diff, which is more useful than a list of names. Two gates
// going red for one cause makes the second one look like a second problem.
const uncommitted = [...generatedNames].filter(
  (name) => !committed.includes(name) && !notGenerated.includes(name),
);

if (notGenerated.length) {
  console.log(
    `Skipped ${notGenerated.length} file(s) in ${BINDINGS_REL} with no ts-rs ` +
      `header (hand-written, so not orphanable): ${notGenerated.join(", ")}`,
  );
}
if (uncommitted.length) {
  console.log(
    `Note: ${uncommitted.length} generated file(s) are not committed — run ` +
      `\`pnpm gen:types\`: ${uncommitted.join(", ")}`,
  );
}

if (orphans.length === 0) {
  console.log(
    `No orphaned bindings: all ${committed.length} generated file(s) in ` +
      `${BINDINGS_REL} are still produced by a Rust DTO.`,
  );
  process.exit(0);
}

// Single line, ASCII only — GitHub renders annotations as one line, so a
// multi-line body would be truncated to its first line on the PR.
if (process.env.GITHUB_ACTIONS === "true") {
  console.log(
    `::error title=Orphaned ts-rs bindings::${orphans.length} file(s) in ` +
      `${BINDINGS_REL} are generated by no Rust DTO - delete them and commit ` +
      `- names in the log of this step.`,
  );
}

console.error(
  `\nOrphaned ts-rs bindings: ${orphans.length} file(s) in ${BINDINGS_REL} ` +
    "that\nno Rust DTO generates any more.\n",
);
for (const name of orphans) console.error(`  ${BINDINGS_REL}/${name}`);
console.error(
  "\nEach of these was generated by a DTO that has since been deleted or\n" +
    "renamed. Nothing regenerates over them, so the bindings diff stays green\n" +
    "while the frontend can still import a type the backend no longer has.\n" +
    "\nFix, from the repo root — delete them, then commit:\n",
);
for (const name of orphans) console.error(`    rm ${BINDINGS_REL}/${name}`);
console.error(
  "\n    git add " +
    BINDINGS_REL +
    '\n    git commit -m "chore: drop orphaned ts-rs bindings"\n' +
    "\nIf one of these is meant to exist, the DTO behind it is gone: restore the\n" +
    "Rust type (with `#[ts(export, export_to = ...)]`) rather than the .ts file,\n" +
    "which is generated output and will not survive the next `pnpm gen:types`.",
);
process.exit(1);
